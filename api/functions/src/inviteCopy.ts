/** The game catalogs (item names, reward kinds, profile labels) and Steam store languages. */
// biome-ignore lint/suspicious/noExplicitAny: JSON catalogs are bundled by webpack.
const catalogs: Record<string, Record<string, string>> = Object.fromEntries(INVITE_LANGUAGES.map(code => [code, require(`@legion/locales/${code}/messages.json`) as any]));
const steamLanguages: Record<string, string | undefined> = Object.fromEntries(INVITE_LANGUAGES.map(code => [code, (require(`@legion/locales/${code}/locale.json`) as {steamLanguages?: string[]}).steamLanguages?.[0]]));

/** A game string in `language`, falling back to English and then the key itself. */
export function gameText(language: InviteLanguage, key: string): string {
  return catalogs[language]?.[key] || catalogs.en?.[key] || key;
}

/** Steam's store language name (`french`, `brazilian`…) for store links. */
export function steamStoreLanguage(language: InviteLanguage): string | undefined {
  return steamLanguages[language];
}

/** Replaces `{placeholders}`; values must already be HTML-escaped. */
export function fill(template: string, values: Record<string, string>): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) => values[key] ?? match);
}
